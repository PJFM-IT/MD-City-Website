const ts = (s) => {
  const ms = Math.round(s * 1000);
  const h = String(Math.floor(ms / 3600000)).padStart(2, "0");
  const m = String(Math.floor((ms % 3600000) / 60000)).padStart(2, "0");
  const sec = String(Math.floor((ms % 60000) / 1000)).padStart(2, "0");
  return `${h}:${m}:${sec}.${String(ms % 1000).padStart(3, "0")}`;
};

const langs = Object.keys(cues[0][2]);
const outDir = path.resolve("public/subtitles");
fs.mkdirSync(outDir, { recursive: true });

for (const lang of [...langs, "en"]) {
  const body = cues
    .map(([[a, b], en, tr], i) => `${i + 1}\n${ts(a)} --> ${ts(b)}\n${lang === "en" ? en : tr[lang]}`)
    .join("\n\n");
  fs.writeFileSync(path.join(outDir, `intro.${lang}.vtt`), `WEBVTT\n\n${body}\n`, "utf8");
}
console.log(`Wrote ${langs.length + 1} subtitle files to ${outDir}`);
